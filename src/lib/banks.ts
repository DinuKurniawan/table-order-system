const normalize = (value: string) =>
  value
    .toLowerCase()
    .replace(/^transfer\s+/, "")
    .replace(/^bank\s+/, "")
    .replace(/[^a-z0-9]/g, "");

export function bankSlugFromLabel(label: string): string | null {
  const key = normalize(label);
  if (!key) return null;
  const match = BANKS.find(
    (bank) => normalize(bank.name) === key || bank.slug.replace(/-/g, "") === key
  );
  return match?.slug ?? null;
}

export function bankBySlug(slug: string | null | undefined): Bank | undefined {
  return slug ? BANKS.find((bank) => bank.slug === slug) : undefined;
}

export function bankLogoUrl(slug: string): string {
  return `/banks/${slug}.svg`;
}
